//! OrbitEngine **AI studio** (editor only, never linked into the player).
//!
//! The full AI game-creation stack, as a pipeline of reviewable steps:
//!
//! 1. **Pitch** ([`Pitch`]): the user's base text and options;
//! 2. **Bible** ([`bible`]): an LLM writes a structured JSON plan (characters,
//!    locations, scenes, variables), validated and repaired with the errors
//!    fed back;
//! 3. **Script** ([`script`]): the LLM writes each scene in the OrbitEngine
//!    DSL, parsed by `orbit_dsl` against a scratch story built from the bible
//!    and repaired the same way;
//! 4. **Assets** ([`assets`]): image prompts from the bible, generated by
//!    ComfyUI / AUTOMATIC1111 / an OpenAI-compatible endpoint, placeholders on
//!    failure;
//! 5. **Implement** ([`implement`]): characters, pictures, variables and
//!    scenes enter the project through the MCP tools, as one undo entry.
//!
//! Providers are traits ([`TextModel`], [`ImageModel`]) so tests run on
//! mocks. Settings (with keys) live in the user config folder
//! ([`StudioSettings`]); the pipeline state lives in the project's
//! `.orbit/ai/` ([`PipelineState`]), which exports never ship.

